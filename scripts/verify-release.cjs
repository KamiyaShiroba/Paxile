// Verify the updater manifest against the exact downloaded installer and public key.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const [manifestPath, installerPath, signaturePath, expectedVersion] = process.argv.slice(2);
if (!expectedVersion) throw new Error('Usage: node scripts/verify-release.cjs latest.json installer.exe installer.exe.sig VERSION');
const config = JSON.parse(fs.readFileSync(path.join(__dirname, '../app/src-tauri/tauri.conf.json'), 'utf8'));
const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
if (manifest.version.replace(/^v/, '') !== expectedVersion.replace(/^v/, '')) throw new Error('Release/version mismatch');
if (!manifest.notes?.trim()) throw new Error('Missing release notes');
const platform = manifest.platforms['windows-x86_64'];
if (!platform) throw new Error('Missing windows-x86_64 updater');
const url = new URL(platform.url);
const browserAsset = url.hostname === 'github.com' && url.pathname.startsWith('/KamiyaShiroba/Paxile/releases/download/') && url.pathname.endsWith('.exe');
const apiAsset = url.hostname === 'api.github.com' && /^\/repos\/KamiyaShiroba\/Paxile\/releases\/assets\/\d+$/.test(url.pathname);
if (url.protocol !== 'https:' || (!browserAsset && !apiAsset)) throw new Error('Unexpected NSIS asset URL');
const signature = fs.readFileSync(signaturePath, 'utf8').trim();
if (platform.signature.trim() !== signature) throw new Error('Manifest signature differs from .sig asset');
const publicText = Buffer.from(config.plugins.updater.pubkey, 'base64').toString('utf8').trim().split(/\r?\n/);
const key = Buffer.from(publicText[1], 'base64');
const lines = Buffer.from(signature, 'base64').toString('utf8').trim().split(/\r?\n/);
const sig = Buffer.from(lines[1], 'base64');
if (sig.length !== 74 || key.length !== 42 || !sig.subarray(2, 10).equals(key.subarray(2, 10))) throw new Error('Invalid signature/key id');
const pub = crypto.createPublicKey({ key: Buffer.concat([Buffer.from('302a300506032b6570032100', 'hex'), key.subarray(10)]), format: 'der', type: 'spki' });
const file = fs.readFileSync(installerPath);
const message = sig.subarray(0, 2).toString() === 'ED' ? crypto.createHash('blake2b512').update(file).digest() : file;
if (!crypto.verify(null, message, pub, sig.subarray(10))) throw new Error('Installer signature verification failed');
if (!lines[2].startsWith('trusted comment: ')) throw new Error('Missing trusted comment');
const globalMessage = Buffer.concat([sig.subarray(10), Buffer.from(lines[2].slice('trusted comment: '.length))]);
if (!crypto.verify(null, globalMessage, pub, Buffer.from(lines[3], 'base64'))) throw new Error('Trusted comment signature failed');
console.log(JSON.stringify({ version: manifest.version, installer: path.resolve(installerPath), sha256: crypto.createHash('sha256').update(file).digest('hex'), signatureVerified: true, manifestVerified: true }));
